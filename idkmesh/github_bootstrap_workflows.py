"""Deterministic C8-D GitHub bootstrap workflow-wrapper rendering.

This module consumes the C8-A GitHubBootstrapPlan and renders only the four
GitHub Actions wrapper files owned by C8-D. It is pure: no filesystem writes,
network calls, GitHub mutations, secret resolution, workflow execution,
dispatch, verification, or integration are performed.

The wrappers are deliberately thin. They never embed orchestration logic: each
one checks out the pinned IDKMesh revision as a runtime directory and invokes a
single runner entry point (``idkmesh github-workflow <phase>``) from it. Every
third-party Action is pinned to a full commit SHA, the IDKMesh runtime to the
bootstrap plan's explicit release tag or SHA, and every job runs with the
least permissions its execution effect needs. No wrapper uses
``pull_request_target``, auto-merges, or grants merge authority.

The runner entry point is a contract, not an implementation: no released
IDKMesh ref provides it yet. Each wrapper therefore probes for it first and
fails closed, so a wrapper pinned to a ref without the runner can neither
succeed vacuously nor silently do something else.
"""

from __future__ import annotations

import re

from idkmesh.github_bootstrap import GitHubBootstrapPlan
from idkmesh.github_bootstrap_render import (
    BootstrapRenderError,
    BootstrapRenderedFile,
    _connections_document,
    _digest,
)


WORKFLOW_PHASE = "C8-D"
IDKMESH_REPOSITORY = "MSKazemi/idkmesh"
RUNNER_COMMAND = "python -m idkmesh.cli github-workflow"
PREVIEW_LABEL = "idkmesh:preview"
DISPATCH_ENVIRONMENT = "idkmesh-dispatch"

# Full commit SHAs, resolved from the upstream tags named in the trailing
# comment. Dependabot does not see these (they are Python strings, not workflow
# files), so a stale pin is a documented follow-up, not a silent one: tests pin
# the shape (40-hex, same SHA for every use of one Action), never the value.
_CHECKOUT = "actions/checkout@11d5960a326750d5838078e36cf38b85af677262 # v4"
_SETUP_PYTHON = "actions/setup-python@a26af69be951a213d495a4c3e4e4022e16d87065 # v5"
_PYTHON_VERSION = "3.12"

_WORKFLOW_PATHS = frozenset(
    {
        ".github/workflows/idkmesh-dispatch.yml",
        ".github/workflows/idkmesh-preview.yml",
        ".github/workflows/idkmesh-status.yml",
        ".github/workflows/idkmesh-verify.yml",
    }
)
_SECRET_NAME = re.compile(r"[A-Z][A-Z0-9_]{0,63}\Z")


def _header(plan: GitHubBootstrapPlan) -> str:
    return (
        "# Generated by `idkmesh init --github` (bootstrap C8-D).\n"
        "# IDKMesh-managed: a re-run replaces this file only while it still\n"
        "# matches its retained generated digest, so local edits are preserved\n"
        "# and reported instead of overwritten.\n"
        f"# Pinned IDKMesh ref: {plan.idkmesh_ref}\n"
        "# Authority: this workflow holds no approval, push, merge, or\n"
        "# repository-administration authority.\n"
    )


def _branch_guard(plan: GitHubBootstrapPlan) -> str:
    # Project policy is read from the protected integration branch only.
    return f"github.ref == 'refs/heads/{plan.default_branch}'"


def _checkout_project() -> str:
    return (
        "      - name: Check out the trusted project revision\n"
        f"        uses: {_CHECKOUT}\n"
        "        with:\n"
        "          persist-credentials: false\n"
    )


def _checkout_runtime(plan: GitHubBootstrapPlan) -> str:
    return (
        "      - name: Check out the pinned IDKMesh runtime\n"
        f"        uses: {_CHECKOUT}\n"
        "        with:\n"
        f"          repository: {IDKMESH_REPOSITORY}\n"
        f'          ref: "{plan.idkmesh_ref}"\n'
        "          path: .idkmesh-runtime\n"
        "          persist-credentials: false\n"
    )


def _setup_python() -> str:
    return (
        "      - name: Set up Python\n"
        f"        uses: {_SETUP_PYTHON}\n"
        "        with:\n"
        f'          python-version: "{_PYTHON_VERSION}"\n'
    )


def _runner_probe() -> str:
    return (
        "      - name: Require the pinned IDKMesh GitHub workflow runner\n"
        "        working-directory: .idkmesh-runtime\n"
        "        run: |\n"
        f"          {RUNNER_COMMAND} --help > /dev/null || {{\n"
        '            echo "::error::The pinned IDKMesh ref does not provide'
        ' the github-workflow runner."\n'
        "            exit 1\n"
        "          }\n"
    )


def _run_runner(phase: str, env: tuple[tuple[str, str], ...]) -> str:
    # Event data reaches the runner through environment variables only; no
    # expression is ever interpolated into a shell script.
    lines = [
        f"      - name: Run IDKMesh {phase}\n",
        "        working-directory: .idkmesh-runtime\n",
        "        env:\n",
    ]
    lines.extend(f"          {name}: {value}\n" for name, value in env)
    lines.append("        run: |\n")
    lines.append(f"          {RUNNER_COMMAND} {phase}\n")
    return "".join(lines)


_COMMON_ENV: tuple[tuple[str, str], ...] = (
    ("IDKMESH_PROJECT_ROOT", "${{ github.workspace }}"),
    ("IDKMESH_REPOSITORY", "${{ github.repository }}"),
    ("IDKMESH_BASE_SHA", "${{ github.sha }}"),
    ("IDKMESH_RUN_ID", "${{ github.run_id }}"),
)
_TOKEN_ENV: tuple[tuple[str, str], ...] = (
    ("IDKMESH_GITHUB_TOKEN", "${{ github.token }}"),
)


def _dispatch_input(name: str, description: str) -> str:
    return (
        f"      {name}:\n"
        f"        description: {description}\n"
        "        required: true\n"
        "        type: string\n"
    )


def _secret_env(plan: GitHubBootstrapPlan) -> tuple[tuple[str, str], ...]:
    """Secret references the dispatch step may read, derived from the seed.

    The names come from the rendered connector seed, so the connector profile
    and the wrapper cannot drift apart. Only the reference is emitted; the
    value is resolved by GitHub at run time inside the protected environment.
    """

    names: list[str] = []
    for connection in _connections_document(plan):
        secret_ref = connection.get("auth", {}).get("secret_ref")
        if not isinstance(secret_ref, str) or not secret_ref.startswith("env:"):
            raise BootstrapRenderError(
                "invalid_secret_reference",
                "connector seed secret_ref must use the env: scheme",
            )
        name = secret_ref[len("env:"):]
        if _SECRET_NAME.fullmatch(name) is None:
            raise BootstrapRenderError(
                "invalid_secret_reference",
                f"unsupported secret reference name: {name!r}",
            )
        if name not in names:
            names.append(name)
    return tuple((name, "${{ secrets." + name + " }}") for name in sorted(names))


def _preview(plan: GitHubBootstrapPlan) -> str:
    return (
        _header(plan)
        + f"""
name: IDKMesh Preview

# Read-only: derives a WorkUnit preview and route explanation for one issue.
# It performs no dispatch. Preview runs only when a maintainer applies the
# `{PREVIEW_LABEL}` label or dispatches the workflow manually.
on:
  issues:
    types: [labeled]
  workflow_dispatch:
    inputs:
{_dispatch_input("issue_number", "Issue number to preview")}
permissions:
  contents: read

concurrency:
  group: idkmesh-preview-${{{{ inputs.issue_number || github.event.issue.number }}}}
  cancel-in-progress: false

jobs:
  preview:
    if: ${{{{ {_branch_guard(plan)} && (github.event_name == 'workflow_dispatch' || github.event.label.name == '{PREVIEW_LABEL}') }}}}
    runs-on: ubuntu-latest
    timeout-minutes: 10
    permissions:
      contents: read
      issues: read
    steps:
"""
        + _checkout_project()
        + _checkout_runtime(plan)
        + _setup_python()
        + _runner_probe()
        + _run_runner(
            "preview",
            _COMMON_ENV
            + _TOKEN_ENV
            + (
                (
                    "IDKMESH_ISSUE_NUMBER",
                    "${{ inputs.issue_number || github.event.issue.number }}",
                ),
                ("IDKMESH_EVENT_PATH", "${{ github.event_path }}"),
            ),
        )
    )


def _dispatch(plan: GitHubBootstrapPlan) -> str:
    return (
        _header(plan)
        + f"""
name: IDKMesh Dispatch

# Explicit, owner-approved candidate dispatch for one previewed WorkUnit. It is
# never triggered by an issue or pull-request event. The job is bound to the
# `{DISPATCH_ENVIRONMENT}` environment, so provider secrets are released only
# after the repository owner's configured approval. Dispatching produces a
# candidate; it never accepts or merges one.
on:
  workflow_dispatch:
    inputs:
{_dispatch_input("issue_number", "Issue number that was previewed")}{_dispatch_input("work_unit_digest", "Digest of the reviewed WorkUnit preview")}{_dispatch_input("connector_id", "Explicit connector id from .idkmesh/connections.json")}
permissions:
  contents: read

concurrency:
  group: idkmesh-dispatch-${{{{ inputs.issue_number }}}}
  cancel-in-progress: false

jobs:
  dispatch:
    if: ${{{{ {_branch_guard(plan)} }}}}
    runs-on: ubuntu-latest
    timeout-minutes: 15
    environment: {DISPATCH_ENVIRONMENT}
    permissions:
      contents: read
      issues: read
    steps:
"""
        + _checkout_project()
        + _checkout_runtime(plan)
        + _setup_python()
        + _runner_probe()
        + _run_runner(
            "dispatch",
            _COMMON_ENV
            + _TOKEN_ENV
            + (
                ("IDKMESH_ISSUE_NUMBER", "${{ inputs.issue_number }}"),
                ("IDKMESH_WORK_UNIT_DIGEST", "${{ inputs.work_unit_digest }}"),
                ("IDKMESH_CONNECTOR_ID", "${{ inputs.connector_id }}"),
            )
            + _secret_env(plan),
        )
    )


def _verify(plan: GitHubBootstrapPlan) -> str:
    return (
        _header(plan)
        + f"""
name: IDKMesh Verify

# Independent verification of one exact candidate revision. The candidate is
# untrusted data: it is checked out into its own directory with no persisted
# credentials, and this job holds read-only permissions and no secrets.
on:
  workflow_dispatch:
    inputs:
{_dispatch_input("work_unit_digest", "Digest of the WorkUnit the candidate answers")}{_dispatch_input("candidate_sha", "Exact 40-character candidate commit SHA")}
permissions:
  contents: read

concurrency:
  group: idkmesh-verify-${{{{ inputs.candidate_sha }}}}
  cancel-in-progress: false

jobs:
  verify:
    if: ${{{{ {_branch_guard(plan)} }}}}
    runs-on: ubuntu-latest
    timeout-minutes: 30
    permissions:
      contents: read
    steps:
      - name: Require an exact candidate commit SHA
        env:
          CANDIDATE_SHA: ${{{{ inputs.candidate_sha }}}}
        run: |
          if [[ ! "$CANDIDATE_SHA" =~ ^[0-9a-f]{{40}}$ ]]; then
            echo "::error::candidate_sha must be a full 40-character lowercase commit SHA."
            exit 1
          fi
"""
        + _checkout_project()
        + _checkout_runtime(plan)
        + "      - name: Check out the exact candidate revision as data\n"
        + f"        uses: {_CHECKOUT}\n"
        + "        with:\n"
        + "          ref: ${{ inputs.candidate_sha }}\n"
        + "          path: .idkmesh-candidate\n"
        + "          persist-credentials: false\n"
        + _setup_python()
        + _runner_probe()
        + _run_runner(
            "verify",
            _COMMON_ENV
            + (
                ("IDKMESH_WORK_UNIT_DIGEST", "${{ inputs.work_unit_digest }}"),
                ("IDKMESH_CANDIDATE_SHA", "${{ inputs.candidate_sha }}"),
                (
                    "IDKMESH_CANDIDATE_DIR",
                    "${{ github.workspace }}/.idkmesh-candidate",
                ),
            ),
        )
    )


def _status(plan: GitHubBootstrapPlan) -> str:
    return (
        _header(plan)
        + f"""
name: IDKMesh Status

# Publishes one bounded, idempotent status comment on an issue from retained
# run evidence. Manual only: automatic chaining from other workflows is an
# explicit later opt-in because evidence derived from untrusted candidates
# must not reach a privileged job implicitly.
on:
  workflow_dispatch:
    inputs:
{_dispatch_input("issue_number", "Issue number to publish status on")}{_dispatch_input("idkmesh_run_id", "IDKMesh run identifier to summarize")}
permissions:
  contents: read

concurrency:
  group: idkmesh-status-${{{{ inputs.issue_number }}}}
  cancel-in-progress: false

jobs:
  status:
    if: ${{{{ {_branch_guard(plan)} }}}}
    runs-on: ubuntu-latest
    timeout-minutes: 10
    permissions:
      contents: read
      issues: write
    steps:
"""
        + _checkout_project()
        + _checkout_runtime(plan)
        + _setup_python()
        + _runner_probe()
        + _run_runner(
            "status",
            _COMMON_ENV
            + _TOKEN_ENV
            + (
                ("IDKMESH_ISSUE_NUMBER", "${{ inputs.issue_number }}"),
                ("IDKMESH_RUN_REFERENCE", "${{ inputs.idkmesh_run_id }}"),
            ),
        )
    )


def render_github_bootstrap_workflows(
    plan: GitHubBootstrapPlan,
) -> tuple[BootstrapRenderedFile, ...]:
    """Render exactly the C8-D entries from a validated bootstrap plan."""

    if not isinstance(plan, GitHubBootstrapPlan):
        raise TypeError("plan must be GitHubBootstrapPlan")

    specs = tuple(item for item in plan.files if item.phase == WORKFLOW_PHASE)
    paths = {item.path for item in specs}
    if paths != _WORKFLOW_PATHS:
        missing = sorted(_WORKFLOW_PATHS - paths)
        extra = sorted(paths - _WORKFLOW_PATHS)
        raise BootstrapRenderError(
            "workflow_plan_mismatch",
            f"C8-D file plan mismatch: missing={missing} extra={extra}",
        )

    renderers = {
        ".github/workflows/idkmesh-dispatch.yml": _dispatch,
        ".github/workflows/idkmesh-preview.yml": _preview,
        ".github/workflows/idkmesh-status.yml": _status,
        ".github/workflows/idkmesh-verify.yml": _verify,
    }

    rendered: list[BootstrapRenderedFile] = []
    for spec in sorted(specs, key=lambda item: item.path):
        content = renderers[spec.path](plan)
        if not content.endswith("\n") or "\t" in content:
            raise BootstrapRenderError(
                "invalid_rendered_content",
                f"{spec.path}: renderer must return tab-free newline-terminated text",
            )
        rendered.append(
            BootstrapRenderedFile(
                path=spec.path,
                ownership=spec.ownership,
                overwrite_policy=spec.overwrite_policy,
                render_source=spec.render_source,
                content=content,
                content_digest=_digest(content),
                size_bytes=len(content.encode("utf-8")),
            )
        )

    return tuple(rendered)
