"""The checked-in TypeScript declarations are a pure function of the contracts.

Issue #746: ``clients/typescript/idkmesh-api.d.ts`` is generated by
``tools/generate_api_types.py`` from ``openapi.yaml`` and the JSON Schemas it
catalogs. These tests regenerate it and require byte equality, so the file can
never drift from the OpenAPI document, and pin the generator's mapping and its
fail-closed behaviour on constructs it does not model.

stdlib ``unittest`` only (no pytest, no YAML package): the PR Gate installs
neither, and the same module is run unchanged on Python 3.11 and 3.13 because
the output is committed and recomputed -- it must not depend on interpreter
version, dict/set order, or float summation.
"""

from __future__ import annotations

import io
import json
import re
import sys
import tempfile
import unittest
from contextlib import redirect_stderr, redirect_stdout
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "tools"))

import generate_api_types as gen  # noqa: E402

OPENAPI = ROOT / "openapi.yaml"
OUTPUT = ROOT / "clients" / "typescript" / "idkmesh-api.d.ts"
DECLARATION = re.compile(r"^export (?:type|interface) ([A-Za-z0-9_$]+)", re.MULTILINE)


def render(schema: dict, key: str = "probe") -> str:
    """Translate one synthetic schema in isolation."""
    comp = gen.Component(key, f"{key}.schema.json", schema, gen.pascal_case(key))
    translator = gen.Translator(gen.Registry({key: comp}))
    return translator.component_type(comp)


def strip_strings_and_comments(text: str) -> str:
    text = re.sub(r"/\*.*?\*/", "", text, flags=re.DOTALL)
    text = re.sub(r"^\s*//.*$", "", text, flags=re.MULTILINE)
    return re.sub(r'"(?:[^"\\]|\\.)*"', '""', text)


class GoldenFileTests(unittest.TestCase):
    @classmethod
    def setUpClass(cls) -> None:
        cls.generated = gen.generate()
        cls.openapi = gen.load_openapi()
        cls.components = gen.load_components(cls.openapi)

    def test_checked_in_file_is_byte_identical_to_regeneration(self) -> None:
        on_disk = OUTPUT.read_bytes()
        self.assertEqual(
            on_disk, self.generated.encode("utf-8"),
            "clients/typescript/idkmesh-api.d.ts is stale; run python tools/generate_api_types.py",
        )

    def test_generation_is_deterministic_and_lf_only(self) -> None:
        self.assertEqual(self.generated, gen.generate())
        self.assertNotIn("\r", self.generated)
        self.assertTrue(self.generated.endswith("\n"))
        self.assertFalse(self.generated.endswith("\n\n"))

    def test_every_component_and_definition_is_declared(self) -> None:
        declared = set(DECLARATION.findall(self.generated))
        registry = gen.Registry(self.components)
        self.assertGreaterEqual(len(self.components), 80, "component scan is vacuous")
        for key, comp in self.components.items():
            self.assertIn(comp.type_name, declared, key)
            for def_key in comp.schema.get("$defs", {}):
                self.assertIn(registry.def_name(comp, def_key), declared, f"{key}#{def_key}")

    def test_no_duplicate_declarations(self) -> None:
        names = DECLARATION.findall(self.generated)
        duplicates = sorted({n for n in names if names.count(n) > 1})
        self.assertEqual([], duplicates)

    def test_every_operation_is_declared(self) -> None:
        paths = self.openapi["paths"]
        self.assertGreaterEqual(len(paths), 10)
        for path, item in paths.items():
            for method in item:
                self.assertIn(json.dumps(f"{method.upper()} {path}"), self.generated)

    def test_no_any_and_no_runtime_code(self) -> None:
        code = strip_strings_and_comments(self.generated)
        self.assertIsNone(re.search(r"\bany\b", code), "generator must never emit `any`")
        for forbidden in ("function ", "const ", "let ", "var ", "import ", "require("):
            self.assertNotIn(forbidden, code)

    def test_brackets_balance(self) -> None:
        code = strip_strings_and_comments(self.generated)
        stack: list[str] = []
        pairs = {")": "(", "]": "[", "}": "{"}
        for ch in code:
            if ch in "([{":
                stack.append(ch)
            elif ch in pairs:
                self.assertTrue(stack and stack.pop() == pairs[ch], f"unbalanced {ch!r}")
        self.assertEqual([], stack)

    def test_every_statement_is_a_terminated_export(self) -> None:
        code = strip_strings_and_comments(self.generated)
        depth = 0
        for line in code.splitlines():
            if depth == 0 and line.strip():
                self.assertTrue(
                    line.startswith("export ") or line.startswith("  |"), f"stray top-level line: {line!r}"
                )
            depth += sum(line.count(c) for c in "([{") - sum(line.count(c) for c in ")]}")
        self.assertEqual(0, depth)

    def test_header_states_the_over_approximation_policy(self) -> None:
        self.assertIn("GENERATED FILE - DO NOT EDIT", self.generated)
        self.assertIn("NOT encoded", self.generated)


class MappingTests(unittest.TestCase):
    def test_scalars_and_integer_widening(self) -> None:
        self.assertEqual("string", render({"type": "string", "minLength": 1}))
        self.assertEqual("number", render({"type": "integer", "minimum": 0}))
        self.assertEqual("number", render({"type": "number"}))
        self.assertEqual("boolean", render({"type": "boolean"}))
        self.assertEqual("null", render({"type": "null"}))

    def test_const_enum_and_nullable(self) -> None:
        self.assertEqual('"x"', render({"const": "x"}))
        self.assertEqual("0", render({"const": 0}))
        self.assertEqual("false", render({"const": False}))
        self.assertEqual('"a" | "b"', render({"enum": ["a", "b"]}))
        self.assertEqual("string | null", render({"type": ["string", "null"]}))
        self.assertEqual("number | null", render({"type": ["integer", "number", "null"]}))

    def test_arrays_tuples_and_empty_array(self) -> None:
        self.assertEqual("string[]", render({"type": "array", "items": {"type": "string"}}))
        self.assertEqual(
            "(string | null)[]",
            render({"type": "array", "items": {"type": ["string", "null"]}}),
        )
        self.assertEqual("[]", render({"type": "array", "maxItems": 0}))
        self.assertEqual("IdkmeshJsonValue[]", render({"type": "array"}))
        self.assertEqual(
            '["a", number]',
            render({
                "type": "array", "minItems": 2, "maxItems": 2,
                "prefixItems": [{"const": "a"}, {"type": "integer"}],
            }),
        )

    def test_objects_required_optional_and_additional_properties(self) -> None:
        text = render({
            "type": "object", "additionalProperties": False, "required": ["a"],
            "properties": {"a": {"type": "string"}, "b-c": {"type": "integer"}},
        })
        self.assertEqual('{\n  a: string;\n  "b-c"?: number;\n}', text)
        self.assertEqual("Record<string, never>", render({"type": "object", "additionalProperties": False}))
        self.assertEqual(
            "{ [key: string]: number }",
            render({"type": "object", "additionalProperties": {"type": "integer"}}),
        )
        self.assertEqual(
            "{ [key: string]: IdkmeshJsonValue }", render({"type": "object"})
        )

    def test_nested_objects_are_indented(self) -> None:
        text = render({
            "type": "object", "required": ["o"], "additionalProperties": False,
            "properties": {"o": {
                "type": "object", "required": ["x"], "additionalProperties": False,
                "properties": {"x": {"type": "string"}},
            }},
        })
        self.assertEqual("{\n  o: {\n    x: string;\n  };\n}", text)

    def test_combinators(self) -> None:
        self.assertEqual("string | null", render({"oneOf": [{"type": "string"}, {"type": "null"}]}))
        self.assertEqual("string | number", render({"anyOf": [{"type": "string"}, {"type": "integer"}]}))
        # A bare ``type`` next to a combinator is redundant and dropped.
        self.assertEqual(
            '"a" | "b"',
            render({"type": "string", "oneOf": [{"const": "a"}, {"const": "b"}]}),
        )
        # Constraint-only members add nothing structural.
        self.assertEqual(
            "{\n  a?: string;\n}",
            render({
                "type": "object", "properties": {"a": {"type": "string"}},
                "anyOf": [{"required": ["a"]}, {"required": ["b"]}],
                "additionalProperties": False,
            }),
        )
        self.assertEqual(
            "{\n  a: string;\n} & {\n  b: number;\n}",
            render({"allOf": [
                {"type": "object", "required": ["a"], "properties": {"a": {"type": "string"}}, "additionalProperties": False},
                {"type": "object", "required": ["b"], "properties": {"b": {"type": "integer"}}, "additionalProperties": False},
            ]}),
        )

    def test_refs_to_defs_and_files(self) -> None:
        defs = gen.Component(
            "outer", "outer.schema.json",
            {"type": "object", "additionalProperties": False, "required": ["d", "o"],
             "properties": {
                 "d": {"$ref": "#/$defs/some_def"},
                 "o": {"$ref": "https://idkmesh.org/schemas/other.schema.json"},
                 "p": {"$ref": "https://idkmesh.org/schemas/other.schema.json#/properties/n"},
             },
             "$defs": {"some_def": {"type": "string"}, "someDef": {"type": "integer"}}},
            "Outer",
        )
        other = gen.Component(
            "other", "other.schema.json",
            {"type": "object", "properties": {"n": {"type": ["string", "null"]}}}, "Other",
        )
        registry = gen.Registry({"outer": defs, "other": other})
        text = gen.Translator(registry).component_type(defs)
        self.assertIn("d: Outer_Some_def;", text)
        self.assertIn("o: Other;", text)
        self.assertIn("p?: (string | null);", text)
        # Definitions that differ only by case style must not collide.
        self.assertNotEqual(registry.def_name(defs, "some_def"), registry.def_name(defs, "someDef"))

    def test_conditionals_are_accepted_when_they_name_declared_properties(self) -> None:
        text = render({
            "type": "object", "additionalProperties": False,
            "required": ["status"],
            "properties": {"status": {"enum": ["a", "b"]}, "extra": {"type": ["string", "null"]}},
            "allOf": [{
                "if": {"properties": {"status": {"const": "a"}}, "required": ["status"]},
                "then": {"required": ["extra"], "not": {"required": ["status"]}},
            }],
        })
        self.assertIn('status: "a" | "b";', text)
        self.assertIn("extra?: string | null;", text)

    def test_names_are_deterministic_pascal_case(self) -> None:
        self.assertEqual("IdkmeshApiErrorV01", gen.pascal_case("idkmesh-api-error-v0.1"))
        self.assertEqual("E025LearnedVerifierResult", gen.pascal_case("e025-learned-verifier-result"))
        self.assertEqual("RoutingReplayV0", gen.pascal_case("routing-replay-v0"))


class FailClosedTests(unittest.TestCase):
    def assertRejects(self, schema: dict, *needles: str) -> None:
        with self.assertRaises(gen.ApiTypeGenerationError) as ctx:
            render(schema)
        message = str(ctx.exception)
        self.assertIn("probe", message)  # names the schema
        for needle in needles:
            self.assertIn(needle, message)

    def test_unsupported_keyword_names_schema_and_pointer(self) -> None:
        self.assertRejects(
            {"type": "object", "properties": {"a": {"type": "string", "dependentSchemas": {}}}},
            "dependentSchemas", "/properties/a",
        )
        self.assertRejects(
            {"type": "object", "patternProperties": {"^x": {"type": "string"}}}, "patternProperties"
        )

    def test_untyped_values_are_refused_not_widened_to_any(self) -> None:
        self.assertRejects(
            {"type": "object", "properties": {"a": {"minLength": 1}}}, "/properties/a", "never 'any'"
        )
        self.assertRejects({"minimum": 1}, "no structural keyword")
        self.assertRejects({"type": "object", "properties": {"a": True}}, "boolean")

    def test_unknown_type_and_bad_enum(self) -> None:
        self.assertRejects({"type": "decimal"}, "decimal")
        self.assertRejects({"enum": []}, "enum")
        self.assertRejects({"const": {"a": 1}}, "scalar")

    def test_mixed_union_would_drop_alternatives(self) -> None:
        self.assertRejects({"anyOf": [{"type": "string"}, {"required": ["a"]}]}, "mixes")

    def test_conditional_branch_naming_undeclared_property_is_refused(self) -> None:
        self.assertRejects(
            {"type": "object", "properties": {"s": {"type": "string"}},
             "allOf": [{"if": {"properties": {"s": {"const": "a"}}},
                        "then": {"properties": {"ghost": {"type": "string"}}}}]},
            "ghost", "undeclared",
        )

    def test_property_with_schema_valued_additional_properties_is_refused(self) -> None:
        self.assertRejects(
            {"type": "object", "properties": {"a": {"type": "string"}},
             "additionalProperties": {"type": "string"}},
            "additionalProperties",
        )

    def test_tuple_that_would_reject_valid_arrays_is_refused(self) -> None:
        self.assertRejects(
            {"type": "array", "prefixItems": [{"type": "string"}], "items": False}, "minItems"
        )

    def test_unresolved_and_foreign_refs_are_refused(self) -> None:
        self.assertRejects({"$ref": "#/$defs/missing"}, "missing")
        self.assertRejects({"$ref": "https://idkmesh.org/schemas/nope.schema.json"}, "not a component")
        self.assertRejects({"$ref": "https://example.com/other.json"}, "unsupported $ref")

    def test_unsupported_construct_in_a_whole_document_fails_generation(self) -> None:
        with tempfile.TemporaryDirectory() as tmp:
            schemas = Path(tmp)
            (schemas / "bad.schema.json").write_text(
                json.dumps({"type": "object", "properties": {"a": {"not_a_keyword": 1}}}),
                encoding="utf-8",
            )
            openapi = {
                "paths": {"/x": {"get": {"responses": {"200": {"description": "ok"}}}}},
                "components": {"schemas": {
                    "bad-v1": '{$ref: "https://idkmesh.org/schemas/bad.schema.json"}'
                }},
            }
            with self.assertRaises(gen.ApiTypeGenerationError) as ctx:
                gen.generate(openapi=openapi, schemas_dir=schemas)
            self.assertIn("bad-v1", str(ctx.exception))
            self.assertIn("not_a_keyword", str(ctx.exception))

    def test_component_name_collision_and_missing_file_are_refused(self) -> None:
        with tempfile.TemporaryDirectory() as tmp:
            schemas = Path(tmp)
            (schemas / "a.schema.json").write_text('{"type": "string"}', encoding="utf-8")
            ref = '{$ref: "https://idkmesh.org/schemas/a.schema.json"}'
            with self.assertRaises(gen.ApiTypeGenerationError) as ctx:
                gen.load_components(
                    {"components": {"schemas": {"x-1": ref, "x.1": ref}}}, schemas
                )
            self.assertIn("both map to", str(ctx.exception))
            with self.assertRaises(gen.ApiTypeGenerationError):
                gen.load_components(
                    {"components": {"schemas": {
                        "gone": '{$ref: "https://idkmesh.org/schemas/gone.schema.json"}'
                    }}},
                    schemas,
                )

    def test_unknown_operation_reference_is_refused(self) -> None:
        writer = gen.OperationWriter({"components": {}}, {})
        with self.assertRaises(gen.ApiTypeGenerationError):
            writer.schema_ref({"$ref": "#/components/schemas/ghost"}, "GET /x")
        with self.assertRaises(gen.ApiTypeGenerationError):
            writer.schema_ref({"enum": "[a, b]"}, "GET /x")


class CommandLineTests(unittest.TestCase):
    def run_main(self, *argv: str) -> tuple[int, str, str]:
        out, err = io.StringIO(), io.StringIO()
        with redirect_stdout(out), redirect_stderr(err):
            code = gen.main(list(argv))
        return code, out.getvalue(), err.getvalue()

    def test_check_passes_on_the_committed_file(self) -> None:
        code, out, _ = self.run_main("--check")
        self.assertEqual(0, code)
        self.assertIn("up to date", out)

    def test_check_fails_on_a_stale_or_missing_file(self) -> None:
        with tempfile.TemporaryDirectory() as tmp:
            stale = Path(tmp) / "stale.d.ts"
            stale.write_text("// stale\n", encoding="utf-8")
            code, _, err = self.run_main("--check", "--output", str(stale))
            self.assertEqual(1, code)
            self.assertIn("stale", err)
            code, _, _ = self.run_main("--check", "--output", str(Path(tmp) / "missing.d.ts"))
            self.assertEqual(1, code)
            self.assertEqual("// stale\n", stale.read_text(encoding="utf-8"))

    def test_write_then_check_round_trips(self) -> None:
        with tempfile.TemporaryDirectory() as tmp:
            target = Path(tmp) / "nested" / "api.d.ts"
            code, _, _ = self.run_main("--output", str(target))
            self.assertEqual(0, code)
            self.assertEqual(OUTPUT.read_bytes(), target.read_bytes())
            self.assertEqual(0, self.run_main("--check", "--output", str(target))[0])

    def test_stdout_mode_writes_nothing(self) -> None:
        with tempfile.TemporaryDirectory() as tmp:
            target = Path(tmp) / "api.d.ts"
            code, out, _ = self.run_main("--stdout", "--output", str(target))
            self.assertEqual(0, code)
            self.assertEqual(OUTPUT.read_text(encoding="utf-8"), out)
            self.assertFalse(target.exists())


if __name__ == "__main__":
    unittest.main()
