#!/usr/bin/env python3
"""X4 synthetic calibration: do pilot forecasts and their intervals hit a KNOWN truth?

SYNTHETIC. Everything here is generated by seeded simulators whose ground truth
is exact. It validates the forecasting machinery of X4 (issue #976, hypothesis
H2); it is not evidence about real coding agents and must never be quoted as an
empirical result. The empirical X4 result is E046 (point forecasts, one feasible
split); real interval coverage still needs the E048 data.

What it does. For each simulated scenario it draws several independent agent
populations of M agents over N tasks, computes the exact population coverage
C(M) and blind-spot floor 1 - C(M) (the same truth E046 and
``forecast_intervals`` use), then draws pilots of size k <= 20 and scores every
(forecaster, bootstrap scheme) pair on bias, mean absolute error, the 0.03
tolerance hit-rate and the empirical coverage of its 95% interval. The
forecasters and the interval machinery are imported unchanged from
``agent_value_forecast`` (frozen, E046) and ``forecast_intervals``.

Declared before the first run (and not changed afterwards):

* tolerance 0.03 absolute error on population coverage (H2);
* an interval is *calibrated* if its pooled empirical coverage is at least 0.90
  for a nominal 0.95;
* verdict at k = 10 (``verdict``): ``falsified`` if no forecaster/scheme has
  MAE <= 0.03 in any scenario; ``supported`` if some forecaster/scheme has
  MAE <= 0.03 and a calibrated interval in every scenario; ``mixed`` otherwise.
* the scenario parameters in ``SCENARIOS`` were fixed without looking at any
  forecaster output and are not tuned to make a forecaster pass.

Pilots inside one population share that population's truth, so they are not
independent trials; per-population coverage is reported next to the pooled
figure for that reason.

Standard library only. Deterministic for a fixed seed; every cell has its own
seed so a single cell can be re-run alone.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import math
import random
import sys
from pathlib import Path
from typing import Callable, Mapping, Sequence

sys.path.insert(0, str(Path(__file__).resolve().parent))
import agent_value_forecast as e046  # noqa: E402
import forecast_intervals as x4  # noqa: E402

CountForecaster = x4.CountForecaster

SEED = 20261014
AGENTS = 60
TASKS = 300
POPULATIONS = 6
PILOTS = 30
REPLICATES = 100
PILOT_SIZES = (3, 5, 10, 20)
PRIMARY_K = 10
TOLERANCE = e046.H2_TOLERANCE
CALIBRATED_AT_LEAST = 0.90
LEVEL = x4.LEVEL
AUDIT_TRIALS = 2

# Frozen scenario parameters. ability ~ N(ability_mean, ability_sd); difficulty
# ~ N(difficulty_mean, difficulty_sd); P(solve) = sigmoid(ability - difficulty).
# ``unsolvable`` is the share of tasks no agent can ever solve (a true blind
# spot); ``families`` > 0 adds a per-family, per-task shock of size
# ``family_sd``, which makes agents of one family fail together (shared model).
SCENARIOS: Mapping[str, Mapping[str, float]] = {
    "rasch_moderate": {"ability_mean": 0.0, "ability_sd": 1.0, "difficulty_mean": 0.5, "difficulty_sd": 2.0, "unsolvable": 0.0, "families": 0, "family_sd": 0.0},
    "rasch_hard_tail": {"ability_mean": 0.0, "ability_sd": 1.0, "difficulty_mean": 1.0, "difficulty_sd": 3.0, "unsolvable": 0.0, "families": 0, "family_sd": 0.0},
    "rasch_unsolvable": {"ability_mean": 0.0, "ability_sd": 1.0, "difficulty_mean": 0.5, "difficulty_sd": 2.0, "unsolvable": 0.10, "families": 0, "family_sd": 0.0},
    "family_clustered": {"ability_mean": 0.0, "ability_sd": 1.0, "difficulty_mean": 0.5, "difficulty_sd": 2.0, "unsolvable": 0.0, "families": 6, "family_sd": 1.5},
}

Rows = dict[str, frozenset]


def stable_seed(*parts: object) -> int:
    """A platform-independent integer seed from arbitrary labels."""
    text = "|".join(str(part) for part in parts)
    return int(hashlib.sha256(text.encode("utf-8")).hexdigest()[:16], 16)


def task_ids(tasks: int = TASKS) -> list[str]:
    return [f"t{t:04d}" for t in range(tasks)]


def simulate_population(scenario: str, rng: random.Random, agents: int = AGENTS, tasks: int = TASKS) -> Rows:
    """One simulated population: agent name -> frozenset of solved task ids."""
    cfg = SCENARIOS[scenario]
    ids = task_ids(tasks)
    difficulty = [rng.gauss(cfg["difficulty_mean"], cfg["difficulty_sd"]) for _ in ids]
    unsolvable = set(rng.sample(range(tasks), round(cfg["unsolvable"] * tasks))) if cfg["unsolvable"] else set()
    families = int(cfg["families"])
    shock = [[rng.gauss(0, cfg["family_sd"]) for _ in ids] for _ in range(families)]
    rows: Rows = {}
    for j in range(agents):
        ability = rng.gauss(cfg["ability_mean"], cfg["ability_sd"])
        offset = shock[j % families] if families else None
        solved = []
        for t, task in enumerate(ids):
            if t in unsolvable:
                continue
            logit = ability - difficulty[t] + (offset[t] if offset else 0.0)
            if logit > -35 and rng.random() < 1 / (1 + math.exp(-logit)):
                solved.append(task)
        rows[f"agent{j:03d}"] = frozenset(solved)
    return rows


def true_coverage(rows: Mapping[str, frozenset], tasks: Sequence[str]) -> float:
    """Exact fraction of tasks some population agent solves (the truth C(M))."""
    return e046.coverage(rows, sorted(rows), frozenset(tasks)) / len(tasks)


Trial = tuple[float, tuple[float, float], float]


def run_trials(
    forecasters: Mapping[str, CountForecaster],
    rows: Mapping[str, frozenset],
    tasks: Sequence[str],
    k: int,
    seed: int,
    pilots: int = PILOTS,
    replicates: int = REPLICATES,
    level: float = LEVEL,
) -> dict[str, list[Trial]]:
    """(point, interval, truth) trials for every ``forecaster/scheme`` key.

    The truth is the exact coverage of the whole population in ``rows``. Pilot i
    is identical whatever ``pilots`` is, because one stream is consumed in order.
    """
    agents = sorted(rows)
    if not 2 <= k < len(agents):
        raise ValueError("pilot size must satisfy 2 <= k < number of agents")
    truth = true_coverage(rows, tasks)
    rng = random.Random(seed)
    trials: dict[str, list[Trial]] = {f"{name}/{scheme}": [] for name in forecasters for scheme in x4.SCHEMES}
    for _ in range(pilots):
        pilot = rng.sample(agents, k)
        columns = [[1 if t in rows[a] else 0 for t in tasks] for a in pilot]
        for name, forecaster in forecasters.items():
            for scheme in x4.SCHEMES:
                point, interval = x4.bootstrap_interval(columns, forecaster, len(agents), scheme, rng, replicates, level)
                trials[f"{name}/{scheme}"].append((point, interval, truth))
    return trials


def run_cell(
    forecasters: Mapping[str, CountForecaster],
    rows: Mapping[str, frozenset],
    tasks: Sequence[str],
    k: int,
    seed: int,
    pilots: int = PILOTS,
    replicates: int = REPLICATES,
    level: float = LEVEL,
) -> dict:
    trials = run_trials(forecasters, rows, tasks, k, seed, pilots, replicates, level)
    truth = true_coverage(rows, tasks)
    return {
        "true_coverage": round(truth, 4),
        "true_floor": round(1 - truth, 4),
        "results": {key: x4.summarize(value, TOLERANCE) for key, value in trials.items()},
    }


def pool(cells: Sequence[Mapping]) -> dict:
    """Pool per-population cells (equal pilot counts) into one row per forecaster/scheme."""
    keys = list(cells[0]["results"])
    pooled = {}
    for key in keys:
        parts = [cell["results"][key] for cell in cells]
        n = sum(part["pilots"] for part in parts)

        def mean(field: str) -> float:
            # math.fsum is correctly rounded on every interpreter. The built-in sum()
            # of floats changed in Python 3.12 (compensated summation), so a committed
            # report pooled with sum() on 3.12 failed to recompute on 3.11.
            return math.fsum(part[field] * part["pilots"] for part in parts) / n

        coverage = mean("interval_coverage")
        pooled[key] = {
            "pilots": n,
            "bias": round(mean("bias"), 4),
            "mae": round(mean("mae"), 4),
            "within_tolerance": round(mean("within_tolerance"), 4),
            "interval_coverage": round(coverage, 4),
            "min_population_coverage": min(part["interval_coverage"] for part in parts),
            "mean_width": round(mean("mean_width"), 4),
        }
    return pooled


def verdict(primary: Mapping[str, Mapping[str, Mapping]]) -> dict:
    """Pre-declared decision rule at k = PRIMARY_K, from {scenario: {key: pooled row}}."""
    keys = list(next(iter(primary.values())))
    accurate = {key: [s for s, rows in primary.items() if rows[key]["mae"] <= TOLERANCE] for key in keys}
    qualified = {
        key: [s for s, rows in primary.items() if rows[key]["mae"] <= TOLERANCE and rows[key]["interval_coverage"] >= CALIBRATED_AT_LEAST]
        for key in keys
    }
    if not any(accurate.values()):
        label = "falsified"
    elif any(len(found) == len(primary) for found in qualified.values()):
        label = "supported"
    else:
        label = "mixed"
    return {
        "verdict": label,
        "scenarios": sorted(primary),
        "accurate_in": {key: found for key, found in accurate.items() if found},
        "accurate_and_calibrated_in": {key: found for key, found in qualified.items() if found},
    }


def make_forecasters() -> dict[str, CountForecaster]:
    return dict(x4.FORECASTERS)


def study(
    seed: int = SEED,
    scenarios: Sequence[str] = tuple(SCENARIOS),
    populations: int = POPULATIONS,
    sizes: Sequence[int] = PILOT_SIZES,
    pilots: int = PILOTS,
    replicates: int = REPLICATES,
    forecasters: Mapping[str, CountForecaster] | None = None,
    agents: int = AGENTS,
    tasks: int = TASKS,
) -> dict:
    forecasters = forecasters or make_forecasters()
    ids = task_ids(tasks)
    report: dict = {}
    primary: dict[str, dict] = {}
    audit = None
    for scenario in scenarios:
        populations_out = []
        cells: dict[int, list[dict]] = {k: [] for k in sizes}
        for index in range(populations):
            rows = simulate_population(scenario, random.Random(stable_seed(seed, "population", scenario, index)), agents, tasks)
            for k in sizes:
                cell_seed = stable_seed(seed, "cell", scenario, index, k)
                cells[k].append(run_cell(forecasters, rows, ids, k, cell_seed, pilots, replicates))
            populations_out.append(round(true_coverage(rows, ids), 4))
            if audit is None:
                audit = {"scenario": scenario, "population": index, "k": PRIMARY_K}
                trials = run_trials(forecasters, rows, ids, PRIMARY_K, stable_seed(seed, "cell", scenario, index, PRIMARY_K), min(AUDIT_TRIALS, pilots), replicates)
                audit["trials"] = {key: [[round(p, 6), [round(lo, 6), round(hi, 6)], round(t, 6)] for p, (lo, hi), t in value] for key, value in trials.items()}
        by_k = {str(k): {"pooled": pool(cells[k]), "populations": cells[k]} for k in sizes}
        report[scenario] = {"parameters": dict(SCENARIOS[scenario]), "population_true_coverage": populations_out, "by_k": by_k}
        if PRIMARY_K in sizes:
            primary[scenario] = by_k[str(PRIMARY_K)]["pooled"]
    return {"scenarios": report, "decision": verdict(primary) if primary else None, "audit_cell": audit}


def main(argv: Sequence[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--out", type=Path)
    parser.add_argument("--seed", type=int, default=SEED)
    parser.add_argument("--populations", type=int, default=POPULATIONS)
    parser.add_argument("--pilots", type=int, default=PILOTS)
    parser.add_argument("--replicates", type=int, default=REPLICATES)
    parser.add_argument("--agents", type=int, default=AGENTS)
    parser.add_argument("--tasks", type=int, default=TASKS)
    parser.add_argument("--sizes", type=int, nargs="+", default=list(PILOT_SIZES))
    args = parser.parse_args(argv)
    summary = {
        "experiment": "X4-synthetic-interval-calibration",
        "status": "SYNTHETIC: seeded simulation with exact ground truth; not evidence about real coding agents",
        "seed": args.seed,
        "agents": args.agents,
        "tasks": args.tasks,
        "populations_per_scenario": args.populations,
        "pilots_per_cell": args.pilots,
        "bootstrap_replicates": args.replicates,
        "pilot_sizes": args.sizes,
        "level": LEVEL,
        "tolerance": TOLERANCE,
        "calibrated_at_least": CALIBRATED_AT_LEAST,
        "primary_k": PRIMARY_K,
        "frozen_e046_sha256": hashlib.sha256(Path(e046.__file__).read_bytes()).hexdigest(),
        "forecast_intervals_sha256": hashlib.sha256(Path(x4.__file__).read_bytes()).hexdigest(),
        **study(args.seed, populations=args.populations, sizes=args.sizes, pilots=args.pilots, replicates=args.replicates, agents=args.agents, tasks=args.tasks),
    }
    text = json.dumps(summary, indent=1) + "\n"
    if args.out:
        args.out.write_text(text, encoding="utf-8")
    sys.stdout.write(json.dumps({"decision": summary["decision"]}, indent=1) + "\n")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
